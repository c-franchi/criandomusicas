 begin perform public.save_musical_gift(g,data,1);raise exception 'Expected owner save guard';exception when others then if sqlerrm<>'gift_forbidden' then raise;end if;end;
 execute 'reset role';
 perform set_config('request.jwt.claims','{}',true);
 execute 'set local role anon';
 if public.get_musical_gift(token)->>'recipient_name'<>'Fixture recipient' then raise exception 'Recipient cannot open valid token';end if;
 if public.get_musical_gift(repeat('0',64)) is not null then raise exception 'Invalid token reveals content';end if;
 begin perform public.musical_gift_action(g,'test');raise exception 'Anonymous mutation allowed';exception when insufficient_privilege then null;end;
