 -- Production and idempotence, with explicit test designation and no fake payment.
 data:=jsonb_build_object('product','short','music_source','new','recipient_name','Short fixture','sender_name','Fixture sender','dedication','Fixture short song','theme','love','occasion','birthday','duration_seconds',15,'has_card',true,'details',jsonb_build_object('story','A test story with more than twenty characters.','style','pop','tone','funny','language','Português','music_type','parodia'));
