 begin perform public.musical_gift_action(g,'submit');raise exception 'Expected missing price guard';exception when others then if sqlerrm<>'gift_price_unavailable' then raise;end if;end;
 begin perform public.musical_gift_action(g,'publish','{"reviewed":true}');raise exception 'Expected unpaid guard';exception when others then if sqlerrm<>'gift_invalid_payment' then raise;end if;end;
